"""Regenerate polygon rasterization regression shaders using an offline glslc."""

__import__("sys").dont_write_bytecode = True

import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslc", default="glslc")
    options = parser.parse_args()
    directory = Path(__file__).resolve().parents[2] / "unit/gpu/shaders"
    output = ["// SPDX-License-Identifier: GPL-2.0-or-later",
              "// Generated by tests/tooling/gpu/generate_raster_polygon.py; do not edit.",
              "#pragma once", "#include <array>", "#include <cstdint>", ""]
    variants = [("vert", "vertex", ["-DCAPTURE=0"]),
                ("vert", "capture", ["-DCAPTURE=1"]),
                ("geom", "geometry", []), ("tesc", "control", []),
                ("tese", "evaluation", []),
                ("frag", "fragment", ["-DPOINT_COORD=1"]),
                ("frag", "facing", ["-DPOINT_COORD=0"]),
                ("frag", "attributes", ["-DATTRIBUTES=1"]),
                ("frag", "early_facing", ["-DEARLY=1"])]
    for shape in range(1, 7):
        for stage, name, defines in list(variants[:5]):
            variants.append((stage, f"{name}_{shape}", [*defines, f"-DSHAPE={shape}"]))
    variants.extend([("vert", "endpoints_vertex", []),
                     ("vert", "endpoints_point_vertex", ["-DPOINT_SIZE_STORAGE=1"]),
                     ("frag", "endpoints_fragment", [])])
    with tempfile.TemporaryDirectory(prefix="raster-polygon-") as temporary:
        for stage, name, defines in variants:
            binary = Path(temporary) / f"{name}.spv"
            source = "raster_endpoints" if name.startswith("endpoints_") else "raster_polygon"
            subprocess.run([options.glslc, "--target-env=vulkan1.1", "-O", *defines,
                            str(directory / f"{source}.{stage}"),
                            "-o", str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack(f"<{len(data) // 4}I", data)
            output.append(f"constexpr std::array<uint32_t, {len(words)}> polygon_{name}{{")
            for index in range(0, len(words), 6):
                output.append("    " + ", ".join(f"0x{word:08x}"
                              for word in words[index:index + 6]) + ",")
            output.extend(["};", ""])
    (directory / "raster_polygon_spirv.hpp").write_text("\n".join(output))


if __name__ == "__main__":
    main()
