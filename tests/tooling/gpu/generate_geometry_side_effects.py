"""Regenerate geometry side-effect regression shaders using an offline glslc."""

__import__("sys").dont_write_bytecode = True

import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslc", default="glslc")
    options = parser.parse_args()
    directory = Path(__file__).resolve().parents[2] / "unit/gpu/shaders"
    output = ["// SPDX-License-Identifier: GPL-2.0-or-later",
              "// Generated by tests/tooling/gpu/generate_geometry_side_effects.py; do not edit.",
              "#pragma once", "#include <array>", "#include <cstdint>", ""]
    variants = [("vert", "vertex", []), ("frag", "fragment", [])]
    for name, shape, used in (("two_strips", 0, 1), ("one_strip", 1, 1),
                              ("no_output", 2, 1), ("unused", 0, 0)):
        for capture in (0, 1):
            variants.append(("geom", f"{name}_{capture}",
                             [f"-DSHAPE={shape}", f"-DUSE_RESULT={used}",
                              f"-DCAPTURE={capture}"]))
    with tempfile.TemporaryDirectory(prefix="gs-side-effects-") as temporary:
        for stage, name, defines in variants:
            binary = Path(temporary) / f"{name}.spv"
            subprocess.run([options.glslc, "--target-env=vulkan1.1", "-O", *defines,
                            str(directory / f"geometry_side_effects.{stage}"),
                            "-o", str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack(f"<{len(data) // 4}I", data)
            output.append(f"constexpr std::array<uint32_t, {len(words)}> gs_{name}{{")
            for index in range(0, len(words), 6):
                output.append("    " + ", ".join(f"0x{word:08x}"
                              for word in words[index:index + 6]) + ",")
            output.extend(["};", ""])
    (directory / "geometry_side_effects_spirv.hpp").write_text("\n".join(output))


if __name__ == "__main__":
    main()
