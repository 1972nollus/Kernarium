"""Regenerate TES transform-feedback shaders using an explicit offline compiler."""

__import__("sys").dont_write_bytecode = True

import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslc", default="glslc")
    options = parser.parse_args()
    directory = Path(__file__).resolve().parents[2] / "unit/gpu/shaders"
    output = ["// SPDX-License-Identifier: GPL-2.0-or-later",
              "// Generated by tests/tooling/gpu/generate_tessellation_feedback.py; do not edit.",
              "#pragma once", "#include <array>", "#include <cstdint>",
              "namespace tessellation_feedback {", ""]
    variants = [("vert", "vertex", 0, 0, 0), ("tesc", "control", 0, 0, 0),
                ("frag", "fragment", 0, 0, 0), ("frag", "constant_fragment", 0, 0, 0)]
    for primitive, name in enumerate(["points", "lines", "triangles", "quads"]):
        for clockwise in ([False, True] if primitive >= 2 else [False]):
            for capture in [False, True]:
                variant = name + ("_cw" if clockwise else "") + ("_capture" if capture else "")
                variants.append(("tese", variant, primitive, int(capture), int(clockwise)))
        variants.append(("tese", name + "_packed_capture", primitive, 1, 0))
    with tempfile.TemporaryDirectory(prefix="tessellation-feedback-") as temporary:
        for stage, name, primitive, capture, clockwise in variants:
            binary = Path(temporary) / f"{name}.spv"
            defines = ["-DCONSTANT_COLOR=1"] if name == "constant_fragment" else []
            subprocess.run([options.glslc, "--target-env=vulkan1.1", "-O", *defines,
                            f"-DPRIMITIVE={primitive}", f"-DCAPTURE={capture}",
                            f"-DPACKED={int(name.endswith('_packed_capture'))}",
                            f"-DCLOCKWISE={clockwise}",
                            str(directory / f"tessellation_feedback.{stage}"),
                            "-o", str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack(f"<{len(data) // 4}I", data)
            output.append(f"constexpr std::array<uint32_t, {len(words)}> {name}{{")
            for index in range(0, len(words), 6):
                output.append("    " + ", ".join(f"0x{word:08x}"
                              for word in words[index:index + 6]) + ",")
            output.extend(["};", ""])
    output.extend(["} // namespace tessellation_feedback", ""])
    (directory / "tessellation_feedback_spirv.hpp").write_text("\n".join(output))


if __name__ == "__main__":
    main()
