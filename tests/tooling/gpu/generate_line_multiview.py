"""Regenerate the embedded line-multiview SPIR-V using an offline glslc."""

__import__("sys").dont_write_bytecode = True

import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslc", default="glslc")
    options = parser.parse_args()
    directory = Path(__file__).resolve().parents[2] / "unit/gpu/shaders"
    output = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "// Generated by tests/tooling/gpu/generate_line_multiview.py; do not edit.",
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "",
    ]
    with tempfile.TemporaryDirectory(prefix="line-multiview-") as temporary:
        for name, stage, defines in (("vert", "vert", []),
                                     ("layer_vert", "vert", ["-DWRITE_LAYER"]),
                                     ("frag", "frag", [])):
            binary = Path(temporary) / f"line_multiview.{name}.spv"
            subprocess.run(
                [options.glslc, "--target-env=vulkan1.1", "-O", *defines,
                 str(directory / f"line_multiview.{stage}"), "-o", str(binary)],
                check=True,
            )
            data = binary.read_bytes()
            words = struct.unpack(f"<{len(data) // 4}I", data)
            output.append(
                f"constexpr std::array<uint32_t, {len(words)}> "
                f"line_multiview_{name}_spirv{{"
            )
            for index in range(0, len(words), 6):
                output.append("    " + ", ".join(
                    f"0x{word:08x}" for word in words[index:index + 6]) + ",")
            output.extend(["};", ""])
    (directory / "line_multiview_spirv.hpp").write_text("\n".join(output))


if __name__ == "__main__":
    main()
