"""Generate the partial gl_Position regression shaders using offline glslc."""

__import__("sys").dont_write_bytecode = True

import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslc", default="glslc")
    parser.add_argument("--spirv-val", help="optional offline SPIR-V validator")
    options = parser.parse_args()
    directory = Path(__file__).resolve().parents[2] / "unit/gpu/shaders"
    output = ["// SPDX-License-Identifier: GPL-2.0-or-later",
              "// Generated by tests/tooling/gpu/generate_partial_position.py; do not edit.",
              "#pragma once", "#include <array>", "#include <cstdint>", ""]
    # -O0 keeps the two separate component stores the test is about; the
    # optimizer would merge them back into one vec4 store.
    variants = [("partial_position.vert", "pp_vertex_split"),
                ("partial_position_only_xy.vert", "pp_vertex_xy"),
                ("partial_position.frag", "pp_fragment"),
                ("partial_position_depth.frag", "pp_fragment_depth")]
    with tempfile.TemporaryDirectory(prefix="partial-position-") as temporary:
        for source, name in variants:
            binary = Path(temporary) / f"{name}.spv"
            subprocess.run([options.glslc, "--target-env=vulkan1.1", "-O0",
                            str(directory / source), "-o", str(binary)], check=True)
            data = binary.read_bytes()
            words = list(struct.unpack(f"<{len(data) // 4}I", data))
            if options.spirv_val:
                subprocess.run([options.spirv_val, "--target-env", "vulkan1.1",
                                str(binary)], check=True)
            output.append(f"constexpr std::array<uint32_t, {len(words)}> {name}{{")
            for index in range(0, len(words), 6):
                output.append("    " + ", ".join(f"0x{word:08x}"
                              for word in words[index:index + 6]) + ",")
            output.extend(["};", ""])
    (directory / "partial_position_spirv.hpp").write_text("\n".join(output))


if __name__ == "__main__":
    main()
