"""Generate the GS invocation/stream regression shaders using offline glslc."""

__import__("sys").dont_write_bytecode = True

import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def line_output(words: list[int]) -> None:
    """Change the GLSL frontend's points output to valid Vulkan multistream lines."""
    cursor = 5
    changed = 0
    while cursor < len(words):
        size, opcode = words[cursor] >> 16, words[cursor] & 0xffff
        if not size or cursor + size > len(words):
            raise ValueError("invalid SPIR-V instruction")
        if opcode == 16 and words[cursor + 2] == 27:  # OpExecutionMode OutputPoints
            words[cursor + 2] = 28  # OutputLineStrip
            changed += 1
        cursor += size
    if changed != 1:
        raise ValueError("expected exactly one OutputPoints execution mode")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslc", default="glslc")
    parser.add_argument("--spirv-val", help="optional offline SPIR-V validator")
    options = parser.parse_args()
    directory = Path(__file__).resolve().parents[2] / "unit/gpu/shaders"
    output = ["// SPDX-License-Identifier: GPL-2.0-or-later",
              "// Generated by tests/tooling/gpu/generate_geometry_invocations.py; do not edit.",
              "#pragma once", "#include <array>", "#include <cstdint>", ""]
    variants = [("vert", "vertex", []), ("frag", "fragment", [])]
    for invocations in (2, 4):
        for explicit in (0, 1):
            variants.append(("geom", f"i{invocations}_end{explicit}",
                             [f"-DINVOCATIONS={invocations}", f"-DEXPLICIT_END={explicit}"]))
    with tempfile.TemporaryDirectory(prefix="geometry-invocations-") as temporary:
        for stage, name, defines in variants:
            binary = Path(temporary) / f"{name}.spv"
            subprocess.run([options.glslc, "--target-env=vulkan1.1", "-O", *defines,
                            str(directory / f"geometry_invocations.{stage}"),
                            "-o", str(binary)], check=True)
            data = binary.read_bytes()
            words = list(struct.unpack(f"<{len(data) // 4}I", data))
            if stage == "geom":
                line_output(words)
                binary.write_bytes(struct.pack(f"<{len(words)}I", *words))
            if options.spirv_val:
                subprocess.run([options.spirv_val, "--target-env", "vulkan1.1",
                                str(binary)], check=True)
            output.append(f"constexpr std::array<uint32_t, {len(words)}> gi_{name}{{")
            for index in range(0, len(words), 6):
                output.append("    " + ", ".join(f"0x{word:08x}"
                              for word in words[index:index + 6]) + ",")
            output.extend(["};", ""])
    (directory / "geometry_invocations_spirv.hpp").write_text("\n".join(output))


if __name__ == "__main__":
    main()
