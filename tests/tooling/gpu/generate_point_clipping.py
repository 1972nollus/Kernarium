"""Regenerate native point-clipping regression shaders with an offline glslc."""

__import__("sys").dont_write_bytecode = True

import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslc", default="glslc")
    options = parser.parse_args()
    directory = Path(__file__).resolve().parents[2] / "unit/gpu/shaders"
    output = ["// SPDX-License-Identifier: GPL-2.0-or-later",
              "// Generated by tests/tooling/gpu/generate_point_clipping.py; do not edit.",
              "#pragma once", "#include <array>", "#include <cstdint>",
              "namespace point_clipping {", ""]
    variants = [("vert", "upstream", 1, 0, 0, 1),
                ("tesc", "control", 1, 0, 0, 0),
                ("frag", "fragment", 1, 0, 0, 0)]
    for stage, name in [("vert", "vertex"), ("geom", "geometry"),
                        ("tese", "evaluation")]:
        for suffix, planes, cull, capture in [("", 1, 0, 0), ("_none", 0, 0, 0),
                                              ("_eight", 8, 0, 0), ("_cull", 0, 1, 0),
                                              ("_capture", 1, 0, 1), ("_effects", 1, 0, 0),
                                              ("_partial", 1, 0, 0)]:
            variants.append((stage, name + suffix, planes, cull, capture, 0))
    with tempfile.TemporaryDirectory(prefix="point-clipping-") as temporary:
        for stage, name, planes, cull, capture, upstream in variants:
            binary = Path(temporary) / f"{name}.spv"
            subprocess.run([options.glslc, "--target-env=vulkan1.1", "-O",
                            f"-DCLIP_PLANES={planes}", f"-DCULL_PLANE={cull}",
                            f"-DCAPTURE={capture}", f"-DUPSTREAM={upstream}",
                            f"-DEFFECTS={int(capture or name.endswith('_effects'))}",
                            f"-DPARTIAL={int(name.endswith('_partial'))}",
                            str(directory / f"point_clipping.{stage}"),
                            "-o", str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack(f"<{len(data) // 4}I", data)
            output.append(f"constexpr std::array<uint32_t, {len(words)}> {name}{{")
            for index in range(0, len(words), 6):
                output.append("    " + ", ".join(f"0x{word:08x}"
                              for word in words[index:index + 6]) + ",")
            output.extend(["};", ""])
    output.extend(["} // namespace point_clipping", ""])
    (directory / "point_clipping_spirv.hpp").write_text("\n".join(output))


if __name__ == "__main__":
    main()
