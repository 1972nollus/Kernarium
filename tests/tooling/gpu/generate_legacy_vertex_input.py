"""Regenerate legacy vertex-input regression shaders using an offline glslc."""

__import__("sys").dont_write_bytecode = True

import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslc", default="glslc")
    options = parser.parse_args()
    directory = Path(__file__).resolve().parents[2] / "unit/gpu/shaders"
    output = ["// SPDX-License-Identifier: GPL-2.0-or-later",
              "// Generated by tests/tooling/gpu/generate_legacy_vertex_input.py; do not edit.",
              "#pragma once", "#include <array>", "#include <cstdint>", ""]
    variants = [("vert", "vertex", ["-DCAPTURE=0"]),
                ("vert", "capture", ["-DCAPTURE=1"]), ("frag", "fragment", [])]
    with tempfile.TemporaryDirectory(prefix="legacy-vertex-input-") as temporary:
        for stage, name, defines in variants:
            binary = Path(temporary) / f"{name}.spv"
            subprocess.run([options.glslc, "--target-env=vulkan1.1", "-O", *defines,
                            str(directory / f"legacy_vertex_input.{stage}"),
                            "-o", str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack(f"<{len(data) // 4}I", data)
            output.append(f"constexpr std::array<uint32_t, {len(words)}> legacy_{name}{{")
            for index in range(0, len(words), 6):
                output.append("    " + ", ".join(f"0x{word:08x}"
                              for word in words[index:index + 6]) + ",")
            output.extend(["};", ""])
    (directory / "legacy_vertex_input_spirv.hpp").write_text("\n".join(output))


if __name__ == "__main__":
    main()
