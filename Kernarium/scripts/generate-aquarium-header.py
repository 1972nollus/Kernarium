"""Generate Kernarium's fixed Aquarium probe from the macOS driver."""

from __future__ import annotations

__import__("sys").dont_write_bytecode = True

import argparse
import importlib.util
from pathlib import Path
import sys
from types import ModuleType


def load_driver(path: Path) -> ModuleType:
    specification = importlib.util.spec_from_file_location(
        "kernarium_webgl_aquarium_driver", path
    )
    if specification is None or specification.loader is None:
        raise RuntimeError(f"cannot load Aquarium driver: {path}")
    module = importlib.util.module_from_spec(specification)
    sys.modules[specification.name] = module
    specification.loader.exec_module(module)
    return module


def generate_header(driver: ModuleType) -> str:
    setup = driver.build_kernarium_setup()
    delimiter = "AQUARIUM"
    if f"){delimiter}\"" in setup:
        raise RuntimeError("Aquarium setup collides with its raw-string delimiter")
    return f"""// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by Kernarium/scripts/generate-aquarium-header.py.
#pragma once

#include <string_view>

namespace kernarium::aquarium {{

inline constexpr std::string_view setup =
    R\"{delimiter}({setup}){delimiter}\";

}} // namespace kernarium::aquarium
"""


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--runner", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args()


def main() -> int:
    options = parse_arguments()
    driver = load_driver(options.runner.resolve())
    content = generate_header(driver)
    destination = options.output.resolve()
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists() and destination.read_text(encoding="utf-8") == content:
        return 0
    destination.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
